import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { readFile } from 'node:fs/promises';

const bundle = await build({ entryPoints: ['src/ai.ts', 'src/data.ts'], bundle: true, format: 'esm', write: false, outdir: 'x' });
const modules = {};
for (const file of bundle.outputFiles) modules[file.path.endsWith('ai.js') ? 'ai' : 'data'] = await import('data:text/javascript;base64,' + Buffer.from(file.contents).toString('base64'));
const { makeAiRequest, parseAiSteps } = modules.ai;
const { ingredients, baseOil } = modules.data;
const items = [ingredients.find(i => i.id === 'broccoli'), ingredients.find(i => i.id === 'tomato'), baseOil];
const request = makeAiRequest({ items, servings: 1, steps: ['将西兰花和圣女果炒熟。', '装盘。'], safety: '蔬菜洗净。' });
assert.equal(request.model, 'deepseek-flash');
assert.equal(request.thinking.type, 'disabled');
assert.equal(request.max_tokens, 900);
assert(!JSON.stringify(request).includes('api_key'));
assert.match(request.messages[1].content, /西兰花 100 g/);
const parsed = parseAiSteps({ choices: [{ finish_reason: 'stop', message: { content: JSON.stringify({ steps: ['把西兰花 100 g 洗净切小朵。', '将西兰花 100 g 与圣女果 100 g 翻炒至熟软。'] }) } }], usage: { total_tokens: 120 } }, items);
assert.equal(parsed.steps.length, 2);
assert.equal(parsed.totalTokens, 120);
assert.throws(() => parseAiSteps({ choices: [{ finish_reason: 'stop', message: { content: '{"steps":["炒熟。","装盘。"]}' } }] }, items), /遗漏了西兰花/);
assert.throws(() => parseAiSteps({ choices: [{ finish_reason: 'length', message: { content: '{}' } }] }, items), /截断/);
const publicHtml = await readFile('docs/index.html', 'utf8');
const aiHtml = await readFile('docs/ai.html', 'utf8');
assert(publicHtml.includes('zawq522qjf'));
assert(publicHtml.includes('ai-controls'));
assert(!aiHtml.includes('zawq522qjf'));
assert(!aiHtml.includes('clarity.ms/tag'));
assert(aiHtml.includes('ai-controls'));
assert(!/sk-[A-Za-z0-9]{20,}/.test(publicHtml + aiHtml));
console.log('通过：AI 请求格式、结果校验、私密页面与无内置密钥检查。');
